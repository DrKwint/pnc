"""Revision closure Part L: regenerate manuscript-facing tables from canonical files.

Every number is read from a canonical result artifact produced in this round. Nothing is
transcribed from a Markdown report, and no value is hardcoded. Tables that cannot be built
from a canonical file emit an explicit `\\PARTIAL{...}` marker rather than a plausible
number, so a missing input can never be mistaken for a real result.

    .venv/bin/python experiments/scripts/make_closure_tables.py
"""
from __future__ import annotations

import csv
import json
import math
import statistics as st
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CL = ROOT / "2026neurips_rebuttal_results" / "revision_experiment_closure"
OUT = CL / "tables_final"
RESULTS = ROOT / "results"


def _rows(p: Path):
    return list(csv.DictReader(open(p))) if p.exists() else []


def _f(x, default=None):
    try:
        v = float(x)
        return v if v == v else default
    except (TypeError, ValueError):
        return default


def _tex_doc(body: str, note: str) -> str:
    return f"% generated by experiments/scripts/make_closure_tables.py\n% {note}\n{body}\n"


def _partial(name: str, why: str) -> str:
    return _tex_doc(f"\\PARTIAL{{{name}: {why}}}", f"NOT GENERATED -- {why}")


# ------------------------------------------------------------------ ImageNet
IMAGENET_MAIN = ["MSP", "Base entropy (T=0.7)", "Mahalanobis", "LLLA-Kron",
                 "SCOD-linear", "Uncorrected perturbation", "P&C"]


def imagenet_vit() -> str:
    rows = {r["method"]: r for r in _rows(CL / "imagenet_final_scores.csv")}
    if not rows:
        return _partial("imagenet_vit", "imagenet_final_scores.csv missing")
    L = [r"\begin{tabular}{lrrrrr}", r"\toprule",
         r"Method & ID err.\ AUROC & Near AUROC & Far AUROC & Near FPR95 & Far FPR95 \\",
         r"\midrule"]
    for m in IMAGENET_MAIN:
        r = rows.get(m)
        if r is None:
            continue
        def cell(k, sk=None):
            v = _f(r[k])
            s = _f(r.get(sk, "")) if sk else None
            if v is None:
                return "--"
            return (f"{v*100:.2f}" if not s else
                    f"{v*100:.2f}\\,$\\pm$\\,{s*100:.2f}")
        L.append(f"{m.replace('&', chr(92) + '&')} & {cell('id_error_auroc')} & "
                 f"{cell('near_auroc', 'near_auroc_std')} & "
                 f"{cell('far_auroc', 'far_auroc_std')} & "
                 f"{cell('near_fpr95')} & {cell('far_fpr95')} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return _tex_doc("\n".join(L),
                    "source: imagenet_final_scores.csv (single canonical evaluator)")


def imagenet_vit_per_dataset() -> str:
    rows = _rows(CL / "imagenet_final_per_dataset.csv")
    if not rows:
        return _partial("imagenet_vit_per_dataset",
                        "imagenet_final_per_dataset.csv missing")
    ds = ["ssb_hard", "ninco", "inaturalist", "textures", "openimage_o"]
    by = defaultdict(dict)
    for r in rows:
        by[r["method"]][r["dataset"]] = _f(r["auroc"])
    L = [r"\begin{tabular}{l" + "r" * len(ds) + "}", r"\toprule",
         "Method & " + " & ".join(d.replace("_", r"\_") for d in ds) + r" \\",
         r"\midrule"]
    for m in IMAGENET_MAIN:
        if m not in by:
            continue
        L.append(f"{m.replace('&', chr(92) + '&')} & " + " & ".join(
            (f"{by[m][d]*100:.2f}" if by[m].get(d) is not None else "--")
            for d in ds) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return _tex_doc("\n".join(L), "source: imagenet_final_per_dataset.csv")


# ------------------------------------------------------------------ MuJoCo
GYM_METRICS = [("rmse_id", "ID RMSE $\\downarrow$"), ("nll_id", "ID NLL $\\downarrow$"),
               ("nll_ood_near", "Near NLL $\\downarrow$"),
               ("nll_ood_mid", "Mid NLL $\\downarrow$"),
               ("nll_ood_far", "Far NLL $\\downarrow$"),
               ("auroc_ood_far", "Far AUROC $\\uparrow$")]
HEADLINE_ENVS = ["Ant-v5", "HalfCheetah-v5", "Hopper-v5"]


def _mujoco_selected(centre="original"):
    rows = [r for r in _rows(CL / "mujoco_original_centered_per_env.csv")
            if r["ridge_center"] == centre]
    by = defaultdict(list)
    for r in rows:
        by[r["env"]].append(r)
    return by


def mujoco_per_env() -> str:
    by = _mujoco_selected()
    if not by:
        return _partial("mujoco_per_env", "mujoco_original_centered_per_env.csv missing")
    L = [r"\begin{tabular}{ll" + "r" * len(GYM_METRICS) + "}", r"\toprule",
         "Env & seeds & " + " & ".join(h for _, h in GYM_METRICS) + r" \\", r"\midrule"]
    for env in HEADLINE_ENVS:
        g = by.get(env, [])
        if not g:
            continue
        cells = []
        for k, _ in GYM_METRICS:
            v = [_f(r[k]) for r in g if _f(r[k]) is not None]
            cells.append(f"{st.mean(v):.2f}\\,$\\pm$\\,{st.stdev(v):.2f}"
                         if len(v) > 1 else (f"{v[0]:.2f}" if v else "--"))
        L.append(f"{env.replace('-v5', '')} & {len(g)} & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return _tex_doc("\n".join(L),
                    "P&C, original-centred ridge; per-(env,seed) size by ID-val NLL; "
                    "source: mujoco_original_centered_per_env.csv")


def mujoco_cross_env() -> str:
    rk = _rows(CL / "mujoco_original_centered_ranks.csv")
    pr = [r for r in _rows(CL / "mujoco_center_paired.csv")
          if r.get("env_scope") == "headline3"]
    if not pr:
        return _partial("mujoco_cross_env", "mujoco_center_paired.csv missing")
    L = [r"\begin{tabular}{lrrrr}", r"\toprule",
         r"Metric & mean $\Delta$ & median $\Delta$ & max $|\Delta|$ & 95\% CI \\",
         r"\midrule"]
    for r in pr:
        L.append(f"{r['metric'].replace('_', chr(92) + '_')} & "
                 f"{_f(r['mean_diff']):+.4f} & {_f(r['median_diff']):+.4f} & "
                 f"{_f(r['max_abs_diff']):.4f} & "
                 f"[{_f(r['ci95_lo']):+.4f}, {_f(r['ci95_hi']):+.4f}] \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return _tex_doc("\n".join(L),
                    "original-centred minus zero-centred, 15 (env,seed) pairs over "
                    "Ant/HalfCheetah/Hopper; source: mujoco_center_paired.csv")


def mujoco_ridge_sensitivity() -> str:
    rows = _rows(CL / "mujoco_ridge_sensitivity_original_centered.csv")
    if not rows:
        return _partial("mujoco_ridge_sensitivity",
                        "mujoco_ridge_sensitivity_original_centered.csv missing")
    cols = [("id_rmse_mean", "ID RMSE"), ("id_nll_mean", "ID NLL"),
            ("near_auroc_mean", "Near AUROC"), ("mid_auroc_mean", "Mid AUROC"),
            ("far_auroc_mean", "Far AUROC"), ("far_nll_mean", "Far NLL")]
    L = [r"\begin{tabular}{lr" + "r" * len(cols) + "}", r"\toprule",
         r"$\lambda$ & cells & " + " & ".join(h for _, h in cols) + r" \\", r"\midrule"]
    for r in sorted(rows, key=lambda x: _f(x["lambda"], 0.0)):
        lam = _f(r["lambda"])
        L.append(f"{lam:g} & {r['n_cells']} & " + " & ".join(
            (f"{_f(r[k]):.4f}" if _f(r[k]) is not None else "--") for k, _ in cols)
            + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return _tex_doc("\n".join(L),
                    "11 envs x 5 seeds x 9 lambda, original-centred; "
                    "source: mujoco_ridge_sensitivity_original_centered.csv")


# ------------------------------------------------------------------ efficiency
def efficiency() -> str:
    fp = CL / "imagenet_efficiency_full_construction.json"
    ms = CL / "imagenet_inference_m_scaling.json"
    if not fp.exists():
        return _partial("efficiency", "imagenet_efficiency_full_construction.json missing")
    e = json.loads(fp.read_text())
    c, s = e["construction"], e["storage"]
    L = [r"\begin{tabular}{lr}", r"\toprule", r"Quantity & Value \\", r"\midrule",
         r"\multicolumn{2}{l}{\emph{Construction} (ViT-B/16, $r{=}2$, $\lambda{=}1000$, "
         r"$K{=}20$, $M{=}20$, 32{,}768 images)} \\",
         f"Feature cache (one backbone pass) & {c['feature_cache_s']:.1f}\\,s \\\\",
         f"Perturbation basis and coefficients & {c['basis_s']:.2f}\\,s \\\\",
         f"Ridge sufficient statistics (20 members) & {c['sufficient_stats_s']:.2f}\\,s \\\\",
         f"Ridge solves (20 members) & {c['ridge_solve_s']:.2f}\\,s \\\\",
         f"\\textbf{{Total post-hoc construction}} & "
         f"\\textbf{{{c['total_construction_s']:.1f}\\,s}} \\\\",
         f"Peak GPU memory & {c['peak_gpu_gib']:.2f}\\,GiB \\\\",
         f"Peak CPU RSS & {c['peak_cpu_rss_gib']:.2f}\\,GiB \\\\", r"\midrule",
         r"\multicolumn{2}{l}{\emph{Storage}} \\",
         f"Base checkpoint & {s['base_checkpoint_mib']:.1f}\\,MiB \\\\",
         f"P\\&C compact representation & {s['pnc_compact_total_mib']:.1f}\\,MiB \\\\",
         f"\\quad per-member coefficients & "
         f"{s['per_member_coefficients_mib']:.3f}\\,MiB \\\\",
         f"\\quad per-member corrected $W_2$, $b_2$ & "
         f"{s['per_member_corrected_W2_b2_mib']:.1f}\\,MiB \\\\",
         f"Base $+$ P\\&C total & {s['pnc_total_with_base_mib']:.1f}\\,MiB \\\\",
         f"20 full checkpoints (\\emph{{derived}}) & "
         f"{s['full_ensemble_20_checkpoints_mib_DERIVED']:.1f}\\,MiB \\\\",
         f"\\textbf{{Ratio}} & \\textbf{{{s['ratio_pnc_over_full_ensemble']*100:.1f}\\%}} \\\\"]
    if ms.exists():
        m = json.loads(ms.read_text())
        base = 64 / m["base_s_per_batch"]
        r20 = next((x for x in m["rows"] if x["M"] == 20), None)
        L += [r"\midrule", r"\multicolumn{2}{l}{\emph{Inference} (batch 64, TITAN X)} \\",
              f"Base ViT-B/16 & {base:.1f}\\,img/s \\\\"]
        if r20:
            L.append(f"P\\&C $M{{=}}20$ & {r20['images_per_s']:.1f}\\,img/s "
                     f"({r20['ratio_vs_base']:.3f}$\\times$) \\\\")
        L.append(f"Marginal cost per member & "
                 f"{m['marginal_ms_per_image_per_member']:.4f}\\,ms/image \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return _tex_doc("\n".join(L),
                    "sources: imagenet_efficiency_full_construction.json, "
                    "imagenet_inference_m_scaling.json")


