TABLES = {
    "imagenet_vit.tex": imagenet_vit,
    "imagenet_vit_per_dataset.tex": imagenet_vit_per_dataset,
    "mujoco_per_env.tex": mujoco_per_env,
    "mujoco_cross_env.tex": mujoco_cross_env,
    "mujoco_ridge_sensitivity.tex": mujoco_ridge_sensitivity,
    "efficiency.tex": efficiency,
    "cifar_ood.tex": cifar_ood,
    "distilbert.tex": distilbert,
}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    made, partial = [], []
    for name, fn in TABLES.items():
        body = fn()
        (OUT / name).write_text(body)
        (partial if "\\PARTIAL" in body else made).append(name)
        print(f"  {'PARTIAL' if '\\PARTIAL' in body else 'ok     '}  {name}")
    print(f"\n{len(made)} generated, {len(partial)} marked PARTIAL -> {OUT}")
    if partial:
        print("PARTIAL tables carry a \\PARTIAL{...} marker so a missing input cannot be "
              "mistaken for a result.")


if __name__ == "__main__":
    main()
